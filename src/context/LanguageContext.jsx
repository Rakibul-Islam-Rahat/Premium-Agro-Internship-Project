export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try { return localStorage.getItem("premium-agro.language") === "bn" ? "bn" : "en"; } catch { return "en"; }
  });
  const changeLanguage = useCallback((next) => {
    const normalized = next === "bn" ? "bn" : "en";
    setLanguage(normalized);
    try { localStorage.setItem("premium-agro.language", normalized); } catch { /* preference may be unavailable */ }
  }, []);
  const t = useCallback((value) => language === "bn" && typeof value === "string" ? (BN[value] ?? value) : value, [language]);
  useEffect(() => { document.documentElement.lang = language === "bn" ? "bn" : "en"; document.documentElement.classList.toggle("lang-bn", language === "bn"); }, [language]);
  const value = useMemo(() => ({ language, changeLanguage, t }), [language, changeLanguage, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}
export function useLanguage() {
  const value = useContext(LanguageContext);
  return value ?? { language: "en", changeLanguage: () => {}, t: (text) => text };
}
